// FetchSpec is the parsed plugins.toml:
//
//	[[plugin]]
//	source = "modrinth:luckperms@v5.4.141-bukkit"
//
//	[[plugin]]
//	source = "hangar:ViaVersion/ViaVersion"
//
//	[[plugin]]
//	source = "url:https://example.com/thing.wasm"
//	sha256 = "..."
type FetchSpec struct {
	Plugins []Want `toml:"plugin"`
}

type Want struct {
	Source string `toml:"source"`
	SHA256 string `toml:"sha256,omitempty"`
	SHA512 string `toml:"sha512,omitempty"`
	// File overrides the stored file name (url sources default to the URL path).
	File string `toml:"file,omitempty"`
}

func LoadFetchSpec(path string) (*FetchSpec, error) {
	data, err := os.ReadFile(path)
	if errors.Is(err, os.ErrNotExist) {
		return &FetchSpec{}, nil
	}
	if err != nil {
		return nil, fmt.Errorf("plugins.toml: %w", err)
	}
	var s FetchSpec
	dec := toml.NewDecoder(bytes.NewReader(data))
	dec.DisallowUnknownFields()
	if err := dec.Decode(&s); err != nil {
		return nil, fmt.Errorf("%s: %w", path, err)
	}
	seen := map[string]bool{}
	for _, w := range s.Plugins {
		if _, err := ParseSource(w.Source); err != nil {
			return nil, fmt.Errorf("%s: %w", path, err)
		}
		if seen[w.Source] {
			return nil, fmt.Errorf("%s: duplicate source %q", path, w.Source)
		}
		seen[w.Source] = true
	}
	return &s, nil
}

type Source struct {
	Kind    string // "modrinth", "hangar", "url"
	Owner   string // hangar only
	Slug    string
	Version string // empty means latest compatible
	URL     string
}

var slugPattern = func(s string) bool {
	if s == "" || len(s) > 64 {
		return false
	}
	for _, r := range s {
		if !(r >= 'a' && r <= 'z' || r >= 'A' && r <= 'Z' || r >= '0' && r <= '9' || r == '-' || r == '_' || r == '.') {
			return false
		}
	}
	return true
}

func ParseSource(s string) (Source, error) {
	kind, rest, ok := strings.Cut(s, ":")
	if !ok || rest == "" {
		return Source{}, fmt.Errorf("source %q: want modrinth:<slug>, hangar:<owner>/<slug> or url:<https url>", s)
	}
	switch kind {
	case "url":
		u, err := url.Parse(rest)
		if err != nil || u.Host == "" || (u.Scheme != "https" && u.Scheme != "http") {
			return Source{}, fmt.Errorf("source %q: invalid url", s)
		}
		return Source{Kind: kind, URL: rest}, nil
	case "modrinth", "hangar":
		name, version, _ := strings.Cut(rest, "@")
		src := Source{Kind: kind, Version: version}
		if kind == "hangar" {
			owner, slug, ok := strings.Cut(name, "/")
			if !ok || !slugPattern(owner) {
				return Source{}, fmt.Errorf("source %q: want hangar:<owner>/<slug>", s)
			}
			src.Owner, name = owner, slug
		}
		if !slugPattern(name) {
			return Source{}, fmt.Errorf("source %q: invalid project slug", s)
		}
		if strings.ContainsAny(version, "/?#") {
			return Source{}, fmt.Errorf("source %q: invalid version", s)
		}
		src.Slug = name
		return src, nil
	}
	return Source{}, fmt.Errorf("source %q: unknown kind %q", s, kind)
}

type LockEntry struct {
	Source  string `toml:"source"`
	Version string `toml:"version"`
	File    string `toml:"file"`
	URL     string `toml:"url"`
	SHA256  string `toml:"sha256,omitempty"`
	SHA512  string `toml:"sha512,omitempty"`
	Runtime string `toml:"runtime"` // "wasm" or "java"
	Fetched string `toml:"fetched"`
}

type Lockfile struct {
	Plugins []LockEntry `toml:"plugin"`
}

func LoadLockfile(path string) (*Lockfile, error) {
	data, err := os.ReadFile(path)
	if errors.Is(err, os.ErrNotExist) {
		return &Lockfile{}, nil
	}
	if err != nil {
		return nil, fmt.Errorf("plugins.lock: %w", err)
	}
	var l Lockfile
	if err := toml.Unmarshal(data, &l); err != nil {
		return nil, fmt.Errorf("%s: %w", path, err)
	}
	return &l, nil
}

func (l *Lockfile) Save(path string) error {
	sort.Slice(l.Plugins, func(i, j int) bool { return l.Plugins[i].Source < l.Plugins[j].Source })
	var buf bytes.Buffer
	buf.WriteString("# Generated by kremenmc from plugins.toml. Do not edit.\n")
	if err := toml.NewEncoder(&buf).Encode(l); err != nil {
		return fmt.Errorf("plugins.lock: %w", err)
	}
	return writeFileAtomic(path, buf.Bytes())
}

// Fetcher resolves FetchSpec entries against Modrinth (API v2), Hangar (API
// v1) or direct URLs, verifies hashes and keeps plugins.lock in sync.
type Fetcher struct {
	Client      *http.Client
	ModrinthAPI string // default https://api.modrinth.com/v2
	HangarAPI   string // default https://hangar.papermc.io/api/v1
	GameVersion string // e.g. "26.3"
	Loaders     []string
	UserAgent   string
	Dir         string // plugins directory
	LockPath    string
	MaxBytes    int64
	// Update re-resolves entries without a pinned version even if locked.
	Update bool
	Log    *slog.Logger
}

const (
	DefaultModrinthAPI = "https://api.modrinth.com/v2"
	DefaultHangarAPI   = "https://hangar.papermc.io/api/v1"
)

var DefaultJavaLoaders = []string{"paper", "spigot", "folia", "bukkit"}

type FetchResult struct {
	Wasm    []string // paths of wasm plugins managed by the lockfile
	Jars    []string // paths of jars for the Java bridge
	Fetched []string // sources downloaded in this run
	Removed []string // files deleted because they left plugins.toml
}

type artifact struct {
	version  string
	url      string
	filename string
	sha256   string
	sha512   string
}

var ErrHashMismatch = errors.New("hash mismatch")

func (f *Fetcher) defaults() {
	if f.Client == nil {
		f.Client = &http.Client{Timeout: 2 * time.Minute}
	}
	if f.ModrinthAPI == "" {
		f.ModrinthAPI = DefaultModrinthAPI
	}
	if f.HangarAPI == "" {
		f.HangarAPI = DefaultHangarAPI
	}
	if len(f.Loaders) == 0 {
		f.Loaders = DefaultJavaLoaders
	}
	if f.UserAgent == "" {
		f.UserAgent = "kremenmc-plugin-fetch/1"
	}
	if f.MaxBytes == 0 {
		f.MaxBytes = 256 << 20
	}
	if f.Log == nil {
		f.Log = slog.Default()
	}
	if f.LockPath == "" {
		f.LockPath = filepath.Join(filepath.Dir(f.Dir), "plugins.lock")
	}
}

// Sync makes the plugins directory match spec. Entries that fail are
// reported in the returned error but do not stop the others.
func (f *Fetcher) Sync(ctx context.Context, spec *FetchSpec) (FetchResult, error) {
	f.defaults()
	var res FetchResult
	if err := os.MkdirAll(f.Dir, 0o755); err != nil {
		return res, fmt.Errorf("fetch: %w", err)
	}
	lock, err := LoadLockfile(f.LockPath)
	if err != nil {
		return res, err
	}
	old := map[string]LockEntry{}
	for _, e := range lock.Plugins {
		old[e.Source] = e
	}
	next := &Lockfile{}
	var errs []error
	for _, want := range spec.Plugins {
		entry, fetched, err := f.syncOne(ctx, want, old[want.Source])
		if err != nil {
			errs = append(errs, fmt.Errorf("%s: %w", want.Source, err))
			if prev, ok := old[want.Source]; ok {
				next.Plugins = append(next.Plugins, prev)
			}
			continue
		}
		if fetched {
			res.Fetched = append(res.Fetched, want.Source)
		}
		next.Plugins = append(next.Plugins, entry)
	}
	keep := map[string]bool{}
	for _, e := range next.Plugins {
		keep[e.File] = true
	}
	for _, e := range lock.Plugins {
		if keep[e.File] || !safeFileName(e.File) {
			continue
		}
		if err := os.Remove(filepath.Join(f.Dir, e.File)); err == nil {
			res.Removed = append(res.Removed, e.File)
		}
	}
	if err := next.Save(f.LockPath); err != nil {
		errs = append(errs, err)
	}
	for _, e := range next.Plugins {
		p := filepath.Join(f.Dir, e.File)
		if e.Runtime == "wasm" {
			res.Wasm = append(res.Wasm, p)
		} else {
			res.Jars = append(res.Jars, p)
		}
	}
	slices.Sort(res.Wasm)
	slices.Sort(res.Jars)
	return res, errors.Join(errs...)
}

func (f *Fetcher) syncOne(ctx context.Context, want Want, prev LockEntry) (LockEntry, bool, error) {
	src, err := ParseSource(want.Source)
	if err != nil {
		return LockEntry{}, false, err
	}
	if prev.Source != "" && f.lockValid(want, src, prev) {
		return prev, false, nil
	}
	var a artifact
	switch src.Kind {
	case "modrinth":
		a, err = f.resolveModrinth(ctx, src)
	case "hangar":
		a, err = f.resolveHangar(ctx, src)
	case "url":
		a, err = f.resolveURL(src, want)
	}
	if err != nil {
		return LockEntry{}, false, err
	}
	if want.File != "" {
		a.filename = want.File
	}
	if !safeFileName(a.filename) {
		return LockEntry{}, false, fmt.Errorf("refusing file name %q (want a plain *.jar or *.wasm name)", a.filename)
	}
	if want.SHA256 == "" && want.SHA512 == "" && a.sha256 == "" && a.sha512 == "" {
		return LockEntry{}, false, errors.New("no hash available; add sha256 or sha512 to plugins.toml")
	}
	sum256, sum512, err := f.download(ctx, a.url, a.filename, map[string]string{
		"sha256":        a.sha256,
		"sha512":        a.sha512,
		"pinned sha256": want.SHA256,
		"pinned sha512": want.SHA512,
	})
	if err != nil {
		return LockEntry{}, false, err
	}
	if prev.File != "" && prev.File != a.filename && safeFileName(prev.File) {
		os.Remove(filepath.Join(f.Dir, prev.File))
	}
	runtime := "java"
	if strings.HasSuffix(a.filename, ".wasm") {
		runtime = "wasm"
	}
	f.Log.Info("fetched plugin", "source", want.Source, "version", a.version, "file", a.filename)
	return LockEntry{
		Source:  want.Source,
		Version: a.version,
		File:    a.filename,
		URL:     a.url,
		SHA256:  sum256,
		SHA512:  sum512,
		Runtime: runtime,
		Fetched: time.Now().UTC().Format(time.RFC3339),
	}, true, nil
}

func (f *Fetcher) lockValid(want Want, src Source, e LockEntry) bool {
	if f.Update && src.Kind != "url" && src.Version == "" {
		return false
	}
	if !safeFileName(e.File) {
		return false
	}
	if want.SHA256 != "" && !strings.EqualFold(want.SHA256, e.SHA256) || want.SHA512 != "" && !strings.EqualFold(want.SHA512, e.SHA512) {
		return false
	}
	h256, h512, err := hashFile(filepath.Join(f.Dir, e.File))
	if err != nil {
		return false
	}
	return strings.EqualFold(h256, e.SHA256) && strings.EqualFold(h512, e.SHA512)
}

func safeFileName(name string) bool {
	return name != "" && name == filepath.Base(name) && !strings.HasPrefix(name, ".") &&
		(strings.HasSuffix(name, ".jar") || strings.HasSuffix(name, ".wasm"))
}

func hashFile(path string) (string, string, error) {
	fh, err := os.Open(path)
	if err != nil {
		return "", "", err
	}
	defer fh.Close()
	h256, h512 := sha256.New(), sha512.New()
	if _, err := io.Copy(io.MultiWriter(h256, h512), fh); err != nil {
		return "", "", err
	}
	return hex.EncodeToString(h256.Sum(nil)), hex.EncodeToString(h512.Sum(nil)), nil
}

func (f *Fetcher) get(ctx context.Context, u string) (*http.Response, error) {
	req, err := http.NewRequestWithContext(ctx, http.MethodGet, u, nil)
	if err != nil {
		return nil, err
	}
	req.Header.Set("User-Agent", f.UserAgent)
	resp, err := f.Client.Do(req)
	if err != nil {
		return nil, err
	}
	if resp.StatusCode != http.StatusOK {
		resp.Body.Close()
		return nil, fmt.Errorf("GET %s: %s", u, resp.Status)
	}
	return resp, nil
}

func (f *Fetcher) getJSON(ctx context.Context, u string, v any) error {
	resp, err := f.get(ctx, u)
	if err != nil {
		return err
	}
	defer resp.Body.Close()
	if err := json.NewDecoder(io.LimitReader(resp.Body, 16<<20)).Decode(v); err != nil {
		return fmt.Errorf("GET %s: %w", u, err)
	}
	return nil
}

// download streams url into the plugins directory, verifying every non-empty
// expected hash before the file becomes visible.
func (f *Fetcher) download(ctx context.Context, u, name string, expect map[string]string) (string, string, error) {
	resp, err := f.get(ctx, u)
	if err != nil {
		return "", "", err
	}
	defer resp.Body.Close()
	tmp, err := os.CreateTemp(f.Dir, ".fetch-*")
	if err != nil {
		return "", "", err
	}
	defer os.Remove(tmp.Name())
	h256, h512 := sha256.New(), sha512.New()
	n, err := io.Copy(io.MultiWriter(tmp, h256, h512), io.LimitReader(resp.Body, f.MaxBytes+1))
	if cerr := tmp.Close(); err == nil {
		err = cerr
	}
	if err != nil {
		return "", "", fmt.Errorf("download %s: %w", u, err)
	}
	if n > f.MaxBytes {
		return "", "", fmt.Errorf("download %s: larger than %d bytes", u, f.MaxBytes)
	}
	sums := map[string]hash.Hash{"sha256": h256, "sha512": h512}
	for label, want := range expect {
		if want == "" {
			continue
		}
		algo := strings.TrimPrefix(label, "pinned ")
		got := hex.EncodeToString(sums[algo].Sum(nil))
		if !strings.EqualFold(got, want) {
			return "", "", fmt.Errorf("%w: %s %s: got %s, want %s", ErrHashMismatch, name, label, got, want)
		}
	}
	if err := os.Rename(tmp.Name(), filepath.Join(f.Dir, name)); err != nil {
		return "", "", err
	}
	return hex.EncodeToString(h256.Sum(nil)), hex.EncodeToString(h512.Sum(nil)), nil
}

type modrinthVersion struct {
	ID            string    `json:"id"`
	VersionNumber string    `json:"version_number"`
	VersionType   string    `json:"version_type"`
	GameVersions  []string  `json:"game_versions"`
	Loaders       []string  `json:"loaders"`
	DatePublished time.Time `json:"date_published"`
	Files         []struct {
		URL      string            `json:"url"`
		Filename string            `json:"filename"`
		Primary  bool              `json:"primary"`
		Hashes   map[string]string `json:"hashes"`
	} `json:"files"`
}

func (f *Fetcher) resolveModrinth(ctx context.Context, src Source) (artifact, error) {
	base := strings.TrimRight(f.ModrinthAPI, "/") + "/project/" + url.PathEscape(src.Slug)
	var versions []modrinthVersion
	if src.Version != "" {
		var v modrinthVersion
		if err := f.getJSON(ctx, base+"/version/"+url.PathEscape(src.Version), &v); err != nil {
			return artifact{}, err
		}
		if !slices.Contains(v.GameVersions, f.GameVersion) {
			f.Log.Warn("pinned plugin version does not list this game version", "source", "modrinth:"+src.Slug, "version", src.Version, "game", f.GameVersion)
		}
		versions = []modrinthVersion{v}
	} else {
		loaders, _ := json.Marshal(f.Loaders)
		games, _ := json.Marshal([]string{f.GameVersion})
		q := url.Values{"loaders": {string(loaders)}, "game_versions": {string(games)}}
		if err := f.getJSON(ctx, base+"/version?"+q.Encode(), &versions); err != nil {
			return artifact{}, err
		}
	}
	var candidates []modrinthVersion
	for _, v := range versions {
		if intersects(v.Loaders, f.Loaders) && (src.Version != "" || slices.Contains(v.GameVersions, f.GameVersion)) {
			candidates = append(candidates, v)
		}
	}
	if len(candidates) == 0 {
		return artifact{}, fmt.Errorf("no version for game %s with loaders %v", f.GameVersion, f.Loaders)
	}
	slices.SortStableFunc(candidates, func(a, b modrinthVersion) int {
		if ar, br := a.VersionType == "release", b.VersionType == "release"; ar != br {
			if ar {
				return -1
			}
			return 1
		}
		return b.DatePublished.Compare(a.DatePublished)
	})
	v := candidates[0]
	idx := -1
	for i, file := range v.Files {
		if file.Primary {
			idx = i
			break
		}
	}
	if idx < 0 {
		for i, file := range v.Files {
			if strings.HasSuffix(file.Filename, ".jar") || strings.HasSuffix(file.Filename, ".wasm") {
				idx = i
				break
			}
		}
	}
	if idx < 0 {
		return artifact{}, fmt.Errorf("version %s has no plugin file", v.VersionNumber)
	}
	file := v.Files[idx]
	return artifact{version: v.VersionNumber, url: file.URL, filename: file.Filename, sha512: file.Hashes["sha512"]}, nil
}

type hangarVersion struct {
	Name    string `json:"name"`
	Channel struct {
		Name string `json:"name"`
	} `json:"channel"`
	Downloads map[string]struct {
		FileInfo *struct {
			Name       string `json:"name"`
			SHA256Hash string `json:"sha256Hash"`
		} `json:"fileInfo"`
		ExternalURL string `json:"externalUrl"`
		DownloadURL string `json:"downloadUrl"`
	} `json:"downloads"`
	PlatformDependencies map[string][]string `json:"platformDependencies"`
}

const hangarPlatform = "PAPER"

func (f *Fetcher) resolveHangar(ctx context.Context, src Source) (artifact, error) {
	base := strings.TrimRight(f.HangarAPI, "/") + "/projects/" + url.PathEscape(src.Slug)
	var project struct {
		Namespace struct {
			Owner string `json:"owner"`
			Slug  string `json:"slug"`
		} `json:"namespace"`
	}
	if err := f.getJSON(ctx, base, &project); err != nil {
		return artifact{}, err
	}
	if !strings.EqualFold(project.Namespace.Owner, src.Owner) {
		return artifact{}, fmt.Errorf("hangar project %s is owned by %s, not %s", src.Slug, project.Namespace.Owner, src.Owner)
	}
	var v hangarVersion
	if src.Version != "" {
		if err := f.getJSON(ctx, base+"/versions/"+url.PathEscape(src.Version), &v); err != nil {
			return artifact{}, err
		}
	} else {
		var page struct {
			Result []hangarVersion `json:"result"`
		}
		q := url.Values{"limit": {"25"}, "offset": {"0"}, "platform": {hangarPlatform}, "platformVersion": {f.GameVersion}}
		if err := f.getJSON(ctx, base+"/versions?"+q.Encode(), &page); err != nil {
			return artifact{}, err
		}
		var found bool
		for _, c := range page.Result {
			if _, ok := c.Downloads[hangarPlatform]; !ok {
				continue
			}
			if !found || strings.EqualFold(c.Channel.Name, "release") && !strings.EqualFold(v.Channel.Name, "release") {
				v, found = c, true
			}
		}
		if !found {
			return artifact{}, fmt.Errorf("no %s version for game %s", hangarPlatform, f.GameVersion)
		}
	}
	d, ok := v.Downloads[hangarPlatform]
	if !ok {
		return artifact{}, fmt.Errorf("version %s has no %s download", v.Name, hangarPlatform)
	}
	a := artifact{version: v.Name, url: d.DownloadURL}
	if d.FileInfo != nil {
		a.filename, a.sha256 = d.FileInfo.Name, d.FileInfo.SHA256Hash
	}
	if a.url == "" {
		a.url = d.ExternalURL
	}
	if a.filename == "" {
		a.filename = urlFileName(a.url)
	}
	if a.url == "" {
		return artifact{}, fmt.Errorf("version %s has no download url", v.Name)
	}
	return a, nil
}

func (f *Fetcher) resolveURL(src Source, want Want) (artifact, error) {
	if want.SHA256 == "" && want.SHA512 == "" {
		return artifact{}, errors.New("url sources require sha256 or sha512")
	}
	u, _ := url.Parse(src.URL)
	if u.Scheme != "https" {
		return artifact{}, errors.New("url sources must use https")
	}
	return artifact{version: "url", url: src.URL, filename: urlFileName(src.URL)}, nil
}

func urlFileName(raw string) string {
	u, err := url.Parse(raw)
	if err != nil {
		return ""
	}
	return filepath.Base(u.Path)
}

func intersects(a, b []string) bool {
	for _, x := range a {
		if slices.Contains(b, x) {
			return true
		}
	}
	return false
}
